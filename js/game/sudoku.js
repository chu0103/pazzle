/**
 * sudoku.js —— 第 9 款游戏「九宫格数独」关卡生成器 + 数据层
 *
 * 玩法（标准 9×9 数独）：
 *   每行 / 每列 / 每个 3×3 宫内 1-9 各出现一次。开局给一部分「给定数」，
 *   玩家把剩下的格子填满即过关。**宽松校验**：过程中不提示对错，
 *   点「检查」才统一标出填错的格；填满且合法立即通关。
 *
 * 数据层职责（与玩法场景解耦）：
 *   1. 位掩码回溯求解器 solveCount(grid, cap) —— 数解（唯一性校验靠它）；
 *   2. 随机完整解 solveOne(grid, rng) —— 先造一张合法终盘；
 *   3. 挖空 dig —— 在保持「解唯一」的前提下随机抠掉 target 个格；
 *   4. generate(seed, blanks) —— 确定性造题（同 seed 同题）；
 *   5. build(n) / buildDaily —— 取第 n 关 / 每日关；
 *   6. starsFor(tier, ms) —— 按用时给 ★ 的唯一真源（阈值单调递增）；
 *   7. 注册 BF.games.sudoku（TOTAL=40，4 档 × 10 关）。
 *
 * 关卡表内联在底部 LEVELS（离线生成、运行时不重算、确定性）。
 * ⚠️ 挖空数是**难度承诺**：档卡副标题写「每局挖 36 空」，所以每关必须
 * 精确挖到该档目标数（verify 里有断言）。生成脚本 tools/gen_sudoku_levels.js
 * 会把结果写回本文件的 LEVELS。
 */
