  var N = 9, CELLS = N * N;
  var FULL = 0x1FF;                    // 9 个候选位

  /* ---------------- 基础索引 ---------------- */

  function rowOf(i) { return (i / N) | 0; }
  function colOf(i) { return i % N; }
  function boxOf(i) { return (((i / N) | 0) / 3 | 0) * 3 + ((i % N) / 3 | 0); }

  var ROW = new Array(CELLS), COL = new Array(CELLS), BOX = new Array(CELLS);
  for (var i = 0; i < CELLS; i++) {
    ROW[i] = rowOf(i); COL[i] = colOf(i); BOX[i] = boxOf(i);
  }

  /* ---------------- 求解器 ---------------- */

  /**
   * 数解（最多数到 cap 个就提前返回）。
   * grid: 长度 81 的数组，0=空，1-9=已填。非法（同行列宫重复）返回 0。
   * 用 MRV（最少候选优先）+ 位掩码，9×9 规模足够快。
   */
  function countSolutions(grid, cap) {
    var rows = new Array(N).fill(0), cols = new Array(N).fill(0), boxes = new Array(N).fill(0);
    var empty = [];
    for (var i = 0; i < CELLS; i++) {
      var v = grid[i];
      if (!v) { empty.push(i); continue; }
      var bit = 1 << (v - 1);
      if ((rows[ROW[i]] & bit) || (cols[COL[i]] & bit) || (boxes[BOX[i]] & bit)) { return 0; }
      rows[ROW[i]] |= bit; cols[COL[i]] |= bit; boxes[BOX[i]] |= bit;
    }
    var count = 0;

    function bt() {
      if (count >= cap) { return; }
      // MRV：找候选最少的空格
      var best = -1, bestMask = 0, bestCnt = 10;
      for (var k = 0; k < empty.length; k++) {
        var idx = empty[k];
        if (grid[idx]) { continue; }
        var mask = FULL & ~(rows[ROW[idx]] | cols[COL[idx]] | boxes[BOX[idx]]);
        var cnt = 0, m = mask;
        while (m) { cnt += m & 1; m >>= 1; }
        if (cnt === 0) { return; }            // 死格 → 此分支无解
        if (cnt < bestCnt) { bestCnt = cnt; best = idx; bestMask = mask; if (cnt === 1) { break; } }
      }
      if (best < 0) { count++; return; }      // 没有空格 → 找到一个解
      var r = ROW[best], c = COL[best], b = BOX[best];
      for (var d = 1; d <= N; d++) {
        var bit = 1 << (d - 1);
        if (!(bestMask & bit)) { continue; }
        grid[best] = d; rows[r] |= bit; cols[c] |= bit; boxes[b] |= bit;
        bt();
        grid[best] = 0; rows[r] &= ~bit; cols[c] &= ~bit; boxes[b] &= ~bit;
        if (count >= cap) { return; }
      }
    }

    bt();
    return count;
  }

  /** 造一张随机合法完整解（rng = U.mulberry32 实例）。失败返回 null（理论上不会） */
  function solveOne(grid, rng) {
    var g = grid.slice();
    var rows = new Array(N).fill(0), cols = new Array(N).fill(0), boxes = new Array(N).fill(0);
    for (var i = 0; i < CELLS; i++) {
      var v = g[i];
      if (!v) { continue; }
      var bit = 1 << (v - 1);
      if ((rows[ROW[i]] & bit) || (cols[COL[i]] & bit) || (boxes[BOX[i]] & bit)) { return null; }
      rows[ROW[i]] |= bit; cols[COL[i]] |= bit; boxes[BOX[i]] |= bit;
    }

    function bt() {
      var best = -1, bestMask = 0, bestCnt = 10;
      for (var k = 0; k < CELLS; k++) {
        if (g[k]) { continue; }
        var mask = FULL & ~(rows[ROW[k]] | cols[COL[k]] | boxes[BOX[k]]);
        var cnt = 0, m = mask;
        while (m) { cnt += m & 1; m >>= 1; }
        if (cnt === 0) { return false; }
        if (cnt < bestCnt) { bestCnt = cnt; best = k; bestMask = mask; if (cnt === 1) { break; } }
      }
      if (best < 0) { return true; }
      var r = ROW[best], c = COL[best], b = BOX[best];
      var ds = [];
      for (var d = 1; d <= N; d++) { if (bestMask & (1 << (d - 1))) { ds.push(d); } }
      U.shuffle(ds, rng);
      for (var q = 0; q < ds.length; q++) {
        var bit = 1 << (ds[q] - 1);
        g[best] = ds[q]; rows[r] |= bit; cols[c] |= bit; boxes[b] |= bit;
        if (bt()) { return true; }
        g[best] = 0; rows[r] &= ~bit; cols[c] &= ~bit; boxes[b] &= ~bit;
      }
      return false;
    }

    return bt() ? g : null;
  }

  /* ---------------- 挖空 ---------------- */

  /**
   * 从完整解出发随机挖空，保持解唯一，最多挖 target 个。
   * 多轮随机顺序（6 轮上限）：每轮把还能唯一挖的挖掉，达不到目标就换顺序再来。
   * 返回实际挖掉的格子索引数组（长度可能 < target，极端seed下）。
   */
  function digHoles(solution, target, rng) {
    var puz = solution.slice();
    var order = [];
    for (var i = 0; i < CELLS; i++) { order.push(i); }
    var removed = [];
    for (var pass = 0; pass < 6 && removed.length < target; pass++) {
      U.shuffle(order, rng);
      for (var k = 0; k < order.length && removed.length < target; k++) {
        var idx = order[k];
        if (!puz[idx]) { continue; }
        var v = puz[idx];
        puz[idx] = 0;
        if (countSolutions(puz, 2) === 1) { removed.push(idx); }
        else { puz[idx] = v; }
      }
    }
    return { puzzle: puz, removed: removed };
  }

  /* ---------------- 造题 ---------------- */

  /** 确定性造题：seed 相同 → 题目相同。返回 { p: 题目81数组, s: 解81数组, blanks } */
  function generate(seed, blanks) {
    var rng = U.mulberry32(seed >>> 0);
    var sol = solveOne(new Array(CELLS).fill(0), rng);
    if (!sol) { return null; }
    var d = digHoles(sol, blanks, rng);
    return { p: d.puzzle, s: sol, blanks: d.removed.length };
  }

