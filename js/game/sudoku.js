  /** 第 n 关的难度配置（从内联表取；表为空时确定性实时生成，仅供离线脚本/调试） */
  function configOf(n) {
    var t = tierOf(n);
    var rec = LEVELS[n - 1];
    var p, s, b;
    if (rec) {
      // 内联表是 81 字符串（省体积），这里统一转成数字数组
      p = rec.p.split('').map(Number);
      s = rec.s.split('').map(Number);
      b = rec.b;
    } else {
      var g = generate(seedOf(n), TIER_BLANKS[t]);
      if (!g) { return null; }
      p = g.p; s = g.s; b = g.blanks;
    }
    return { tier: t, blanks: b, puzzle: p, solution: s };
  }

  /* ---------------- build ---------------- */

  function build(n) {
    n = Math.max(1, Math.min(TOTAL, n | 0));
    var cfg = configOf(n);
    if (!cfg) { throw new Error('数独第 ' + n + ' 关生成失败'); }
    return {
      id: 'sudoku',
      level: n,
      tier: cfg.tier,
      tierName: TIER_NAMES[cfg.tier],
      blanks: cfg.blanks,
      given: cfg.puzzle.slice(),          // 0=空格
      solution: cfg.solution.slice(),
      daily: false
    };
  }

  function buildDaily() {
    var seed = U.seedFromDate(new Date());
    var g = generate(seed, DAILY_BLANKS);
    if (!g) { throw new Error('每日数独生成失败'); }
    return {
      id: 'sudoku',
      level: 0,
      tier: 1,
      tierName: TIER_NAMES[1],
      blanks: g.blanks,
      given: g.p.slice(),
      solution: g.s.slice(),
      daily: true
    };
  }

