  function thresholdsFor(tier) { return STAR_MS[Math.max(0, Math.min(3, tier | 0))]; }

  function starsFor(tier, ms) {
    var th = thresholdsFor(tier);
    if (ms <= th.t3) { return 3; }
    if (ms <= th.t2) { return 2; }
    return 1;
  }

